-- Run this entire script in the Supabase SQL Editor

-- 1. Create table for College
CREATE TABLE public.college (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    address TEXT,
    semester TEXT,
    year TEXT,
    logo TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Create table for Students
CREATE TABLE public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usn TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    branch TEXT NOT NULL,
    semester INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 3. Create table for Classrooms
CREATE TABLE public.classrooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room TEXT NOT NULL UNIQUE,
    rows INTEGER NOT NULL,
    cols INTEGER NOT NULL,
    capacity INTEGER NOT NULL,
    "benchCapacity" INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Create table for Exams
CREATE TABLE public.exams (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    semester INTEGER NOT NULL,
    date TEXT NOT NULL,
    time TEXT NOT NULL,
    "subjectCode" TEXT NOT NULL,
    "subjectName" TEXT DEFAULT '',
    "blockNo" TEXT DEFAULT '',
    duration INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. Create table for Rules
CREATE TABLE public.rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "separateBranches" BOOLEAN DEFAULT TRUE,
    "noSameBranchLeftRight" BOOLEAN DEFAULT TRUE,
    "noSameBranchFrontBack" BOOLEAN DEFAULT TRUE,
    "alternateBranch" BOOLEAN DEFAULT TRUE,
    "maintainUsnOrder" BOOLEAN DEFAULT FALSE,
    "fillRoomCompletely" BOOLEAN DEFAULT TRUE,
    "avoidEmptyBenches" BOOLEAN DEFAULT TRUE,
    "randomizeSeats" BOOLEAN DEFAULT FALSE,
    "benchMode" INTEGER DEFAULT 1,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. Create table for Invigilators
CREATE TABLE public.invigilators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room TEXT NOT NULL,
    faculty TEXT NOT NULL,
    time TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 7. Create table for Arrangements
CREATE TABLE public.arrangements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    result JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 8. Create table for Activity
CREATE TABLE public.activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text TEXT NOT NULL,
    time TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

